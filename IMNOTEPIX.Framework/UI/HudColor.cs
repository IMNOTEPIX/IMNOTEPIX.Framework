    public static class HudColorExtensions
    {
        /// <summary>
        /// Gets the RGBA value of the specified HUD color.
        /// </summary>
        public static Color GetColor(this HudColor hudColor)
        {
            var r = new OutputArgument();
            var g = new OutputArgument();
            var b = new OutputArgument();
            var a = new OutputArgument();

            // NOTE: GET_HUD_COLOUR - verify this exact Hash member name exists in your
            // SHVDN build (it's the standard R* native, but Hash enum member spelling
            // can shift between SHVDN versions). Signature: (int hudColour, int* r, int* g, int* b, int* a)
            Function.Call(Hash.GET_HUD_COLOUR, (int)hudColor, r, g, b, a);

            return Color.FromArgb(a.GetResult<int>(), r.GetResult<int>(), g.GetResult<int>(), b.GetResult<int>());
        }

        /// <summary>
        /// Sets the RGBA value of the specified HUD color.
        /// </summary>
        public static void SetColor(this HudColor hudColor, Color color)
            => Function.Call(Hash.REPLACE_HUD_COLOUR_WITH_RGBA, (int)hudColor, color.R, color.G, color.B, color.A);

